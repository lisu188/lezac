    case 0xbe9:logic(lo(r.ax),true);r.ip=0xbeb;break;
    case 0xbeb:branch(flag(0x40),0xc65,0xbed);break;
    case 0xbed:arithmetic(lo(r.ax),lo(r.cx),true,true);r.ip=0xbef;break;
